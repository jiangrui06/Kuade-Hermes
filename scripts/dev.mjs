import { spawn } from 'node:child_process';
import { build } from 'esbuild';
import { createServer } from 'vite';
import electron from 'electron';
await build({ entryPoints: ['src/main/index.ts'], outfile: 'dist/main/index.js', platform: 'node', format: 'esm', bundle: true, packages: 'external', sourcemap: true });
await build({ entryPoints: ['src/preload/index.ts'], outfile: 'dist/preload/index.cjs', platform: 'node', format: 'cjs', bundle: true, external: ['electron'] });
const server = await createServer();
await server.listen();
const env = { ...process.env, KUADE_DEV_URL: 'http://127.0.0.1:5178' };
delete env.ELECTRON_RUN_AS_NODE;
const child = spawn(electron, ['.'], { stdio: 'inherit', env, windowsHide: true });
child.on('exit', async code => { await server.close(); process.exit(code ?? 0); });
process.on('SIGINT', () => child.kill());
