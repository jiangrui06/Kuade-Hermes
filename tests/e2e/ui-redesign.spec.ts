import { execFileSync } from 'node:child_process';
import { test, expect, _electron as electron } from '@playwright/test';
import { createServer } from 'node:http';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { randomUUID } from 'node:crypto';

test('完整界面：初次引导、模型批选、任务检索、全部页面与窄窗口', async () => {
  const root = resolve('.cache/ui-redesign-' + randomUUID()); await mkdir(root, { recursive: true });
  const server = createServer(async (request, response) => {
    if (request.method === 'GET') { response.setHeader('Content-Type', 'application/json'); response.end(JSON.stringify({ data: [{ id: 'design-alpha' }, { id: 'design-beta' }] })); return; }
    let raw = ''; for await (const chunk of request) raw += chunk; const body = JSON.parse(raw);
    const content = body.tools?.length ? '## 已完成界面检查\n\n- 项目保存在本机\n- 模型可以自由切换\n\n```ts\nconst project = "Kuade";\n```' : '界面验收任务';
    response.writeHead(200, { 'Content-Type': 'text/event-stream' });
    response.end('data: ' + JSON.stringify({ id: 'ui', object: 'chat.completion.chunk', created: 1, model: body.model, choices: [{ index: 0, delta: { content }, finish_reason: 'stop' }] }) + '\n\ndata: [DONE]\n\n');
  });
  await new Promise<void>(done => server.listen(0, '127.0.0.1', done)); const port = (server.address() as any).port;
  const env: Record<string, string> = { ...Object.fromEntries(Object.entries(process.env).filter((entry): entry is [string, string] => entry[1] !== undefined)), KUADE_USER_DATA: resolve(root, 'app') }; delete env.ELECTRON_RUN_AS_NODE;
  const executablePath = process.env.KUADE_TEST_EXECUTABLE;
  const app = await electron.launch({ ...(executablePath ? { executablePath } : {}), args: executablePath ? [] : ['.'], cwd: resolve('.'), env });
  const page = await app.firstWindow(); let passed = false;
  const capture = async (name: string) => {
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: resolve(root, name + '.png') });
  };
  try {
    await expect(page.getByText('本机运行', { exact: true })).toBeVisible({ timeout: 130000 });
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1440, 960));
    await expect(page.getByLabel('发送任务', { exact: true })).toBeDisabled();
    await capture('01-welcome');
    await page.getByRole('button', { name: '连接我的模型' }).click();
    await page.getByLabel('连接名称', { exact: true }).fill('我的模型服务');
    await page.getByLabel('API 地址', { exact: true }).fill(`http://127.0.0.1:${port}/v1`);
    await expect(page.getByRole('checkbox', { name: 'design-beta', exact: true })).toBeVisible();
    await page.getByRole('button', { name: '选择当前结果' }).click();
    await expect(page.getByRole('checkbox', { name: 'design-alpha', exact: true })).toBeChecked();
    await expect(page.getByRole('checkbox', { name: 'design-beta', exact: true })).toBeChecked();
    await expect(page.getByRole('button', { name: '保存连接', exact: true })).toBeInViewport();
    await capture('02-models');
    await page.getByRole('button', { name: '保存连接' }).click();
    await page.getByRole('button', { name: '开始对话', exact: true }).click();
    await page.getByLabel('当前模型').selectOption({ label: 'design-beta' });
    await expect(page.getByLabel('当前模型').locator('optgroup')).toHaveCount(1);
    await page.getByRole('button', { name: '读懂项目', exact: true }).click();
    await expect(page.getByLabel('任务需求')).not.toHaveValue('');
    await capture('03-ready');
    await page.getByLabel('发送任务', { exact: true }).click();
    await expect(page.getByRole('heading', { name: '已完成界面检查' })).toBeVisible();
    await expect(page.getByLabel('发送任务', { exact: true })).toBeVisible();
    await capture('04-conversation');
    await page.getByRole('button', { name: '任务记录', exact: true }).click();
    await page.getByRole('button', { name: /^重命名 / }).first().click();
    await page.getByLabel('任务名称', { exact: true }).fill('我的界面检查');
    await page.getByRole('button', { name: '保存名称', exact: true }).click();
    await page.getByLabel('搜索任务').fill('我的界面');
    await expect(page.locator('.task-record')).toHaveCount(1);
    await capture('05-tasks');
    await page.getByLabel('搜索任务').fill('没有这个任务');
    await expect(page.getByRole('heading', { name: '没有匹配的任务' })).toBeVisible();
    const project = resolve(root, 'app', '默认工作区');
    execFileSync('git', ['init', project]);
    execFileSync('git', ['-C', project, 'config', 'core.autocrlf', 'false']);
    await writeFile(resolve(project, 'review.txt'), 'original\n');
    execFileSync('git', ['-C', project, 'add', 'review.txt']);
    await writeFile(resolve(project, 'review.txt'), 'updated by task\n');
    await writeFile(resolve(project, 'README.md'), '# 新文件内容\n\n运行 npm start 查看结果。\n');
    await page.getByRole('button', { name: '代码变更', exact: true }).click();
    await expect(page.getByRole('heading', { name: '代码变更', exact: true })).toBeVisible();
    await expect(page.locator('.diff-view')).toContainText('+updated by task');
    await capture('06-changes');
    await page.getByRole('button', { name: '查看 README.md', exact: true }).click();
    await expect(page.locator('.new-file-preview')).toContainText('运行 npm start');
    await capture('06-new-file');
    await page.getByRole('button', { name: '查看 review.txt', exact: true }).click();
    await expect(page.locator('.diff-view')).toContainText('+updated by task');
    await expect(page.locator('.diff-view')).not.toContainText('新文件内容');
    await page.getByRole('button', { name: '恢复 review.txt', exact: true }).click();
    await page.getByRole('button', { name: '保留修改', exact: true }).click();
    expect(await readFile(resolve(project, 'review.txt'), 'utf8')).toBe('updated by task\n');
    await page.getByRole('button', { name: '恢复 review.txt', exact: true }).click();
    await page.getByRole('button', { name: '确认恢复此文件', exact: true }).click();
    await expect(page.getByRole('button', { name: '查看 review.txt', exact: true })).toHaveCount(0);
    await expect(page.getByRole('button', { name: '查看 README.md', exact: true })).toBeVisible();
    expect(await readFile(resolve(project, 'review.txt'), 'utf8')).toBe('original\n');
    await page.getByRole('button', { name: '回到任务继续修改', exact: true }).click();
    await expect(page.getByLabel('任务需求')).toBeVisible();
    await page.getByRole('button', { name: '工具与技能', exact: true }).click();
    await expect(page.getByRole('switch')).toHaveCount(4);
    await expect(page.getByLabel('MCP 配置')).not.toBeVisible();
    await expect(page.getByRole('region', { name: '项目技能' })).toBeVisible();
    await capture('07-tools');
    await page.getByText('高级配置 · 自定义 MCP', { exact: true }).click();
    await expect(page.getByLabel('MCP 配置')).toBeVisible();
    await page.getByLabel('MCP 配置').fill('{');
    await page.getByRole('button', { name: '保存并重新加载' }).click();
    await expect(page.getByRole('status').filter({ hasText: '配置格式有误' })).toBeVisible();
    await page.getByRole('button', { name: '放弃修改' }).click();
    await expect(page.getByLabel('MCP 配置')).toHaveValue(/mcpServers/);
    // A local fixture under the preset key checks the real toggle/save/reload path without downloading or authorizing external services.
    await page.getByLabel('MCP 配置').fill(JSON.stringify({ mcpServers: { github: { command: process.execPath, args: [resolve('tests/fixtures/mcp.mjs'), resolve(root, 'toggle-proof.txt')], disabled: true } } }));
    await page.getByRole('button', { name: '保存并重新加载' }).click();
    await expect(page.getByRole('status').filter({ hasText: '配置已保存' })).toBeVisible();
    await page.getByText('高级配置 · 自定义 MCP', { exact: true }).click();
    const toggle = page.getByRole('switch', { name: 'GitHub', exact: true });
    await expect(toggle).toHaveAttribute('aria-checked', 'false');
    await toggle.click();
    await expect(toggle).toHaveAttribute('aria-checked', 'true');
    await page.getByText('查看连接状态', { exact: true }).click();
    await expect(page.getByRole('region', { name: '扩展运行状态' })).toContainText('1 个工具已注册');
    await capture('07-tools-connected');
    await toggle.click();
    await expect(toggle).toHaveAttribute('aria-checked', 'false');
    expect(await page.evaluate(async () => (await window.kuade.call('extensions/read')).mcpServers.github.disabled)).toBe(true);
    await page.getByRole('button', { name: '自我迭代', exact: true }).click();
    await expect(page.getByRole('button', { name: '开始迭代并自动更新' })).toBeDisabled();
    await capture('08-iteration');
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1000, 760));
    for (const [id, title] of [['tools', '工具与技能'], ['models', '模型连接'], ['tasks', '任务记录'], ['iteration', '自我迭代'], ['changes', '代码变更'], ['conversation', '工作台']]) {
      await page.getByRole('button', { name: title, exact: true }).click();
      if (id === 'changes') await expect(page.getByRole('button', { name: '刷新修改' })).toBeEnabled();
      await capture('narrow-' + id);
      await expect(page.getByRole('button', { name: '新任务' })).toBeVisible();
    }
    await expect(page.getByLabel('任务需求')).toBeVisible();
    await page.getByRole('button', { name: '新任务' }).click();
    await capture('narrow-welcome');
    await expect(page.getByRole('button', { name: '开发新功能', exact: true })).toBeVisible();
    passed = true;
  } finally {
    await page.screenshot({ path: resolve(root, 'last-state.png') }).catch(() => {});
    await app.close(); server.closeAllConnections(); await new Promise<void>(done => server.close(() => done()));
    await writeFile(resolve(root, 'acceptance.json'), JSON.stringify({ status: passed ? 'passed' : 'failed', root, provider: 'controlled local SSE', executablePath: executablePath || 'development Electron', checks: ['onboarding', 'batch model selection', 'starter draft', 'conversation', 'rename and search', 'six pages', 'advanced MCP draft error and discard', 'iteration validation', '1000x760 layout'] }, null, 2));
    console.log('完整界面验收证据：', root);
  }
});
